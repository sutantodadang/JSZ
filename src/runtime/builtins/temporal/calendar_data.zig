//! Wave 47b: tabulated month data for the calendars whose year shape has no
//! closed form.
//!
//! The Chinese and Korean (dangi) lunisolar calendars place their months by
//! astronomical new moons and solar terms, and Umm al-Qura is a published table
//! of sighted crescents — none of the three can be derived from arithmetic
//! rules the way the other calendars in `calendar.zig` can. Each year is stored
//! as its start (epoch day of month 1, day 1) plus a `shape` word: bits 0..12
//! give each ordinal month's length (set => 30 days, clear => 29) and bits
//! 13..16 give the ordinal position of the leap month, or 0 when the year has
//! none.
//!
//! Generated from ICU's own calendar implementations (via Node's `Intl`), so
//! these agree with the reference implementation test262 is written against.
//! Outside the tabulated range the callers extrapolate; see `calendar.zig`.

/// Ordinal position of the leap month within its year, or 0 for a common year.
pub inline fn leapOrdinal(shape: u32) u8 {
    return @intCast(shape >> 13);
}

/// Length of the `month`-th (1-based) month of a year with this shape.
pub inline fn monthLength(shape: u32, month: u8) u8 {
    return if (shape & (@as(u32, 1) << @intCast(month - 1)) != 0) 30 else 29;
}


